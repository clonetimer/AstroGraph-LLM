"""Bounded consistency-based diagnosis primitives.

This module implements the deterministic conflict -> hitting-set portion of a
model-based diagnosis (MBD) engine.  It deliberately separates subset-minimal
from minimum-cardinality diagnoses and exposes search truncation instead of
silently treating a partial search as complete.

The implementation follows the standard Reiter/GDE relation between conflicts
and diagnoses: a diagnosis must hit every admitted conflict.  It is a generic
reasoning core; system-specific conflicts must be generated by an independently
admitted model/consistency checker.
"""
from __future__ import annotations

import hashlib
import json
from collections.abc import Iterable, Sequence
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, model_validator


def _digest(value: Any) -> str:
    raw = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


class ModelConflict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    conflict_id: str = Field(min_length=1)
    fault_ids: tuple[str, ...] = Field(min_length=1)
    source_ids: tuple[str, ...] = ()
    explanation: str = ""

    @model_validator(mode="after")
    def unique_faults(self) -> "ModelConflict":
        if tuple(sorted(set(self.fault_ids))) != tuple(sorted(self.fault_ids)):
            raise ValueError("fault_ids must be unique and deterministically sorted")
        return self


class MinimalDiagnosisCandidate(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    diagnosis_id: str = Field(min_length=1)
    fault_ids: tuple[str, ...]
    cardinality: int = Field(ge=0)
    hits_all_conflicts: bool = True
    subset_minimal: bool = True
    minimum_cardinality: bool = False

    @model_validator(mode="after")
    def cardinality_matches(self) -> "MinimalDiagnosisCandidate":
        if self.cardinality != len(self.fault_ids):
            raise ValueError("cardinality must equal len(fault_ids)")
        if tuple(sorted(set(self.fault_ids))) != self.fault_ids:
            raise ValueError("fault_ids must be unique and sorted")
        return self


class MinimalDiagnosisResult(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    schema_version: str = "astrograph-model-based-minimal-diagnosis.v1"
    conflicts: tuple[ModelConflict, ...]
    subset_minimal_diagnoses: tuple[MinimalDiagnosisCandidate, ...]
    minimum_cardinality_diagnoses: tuple[MinimalDiagnosisCandidate, ...]
    search_complete: bool
    search_nodes: int = Field(ge=0)
    max_cardinality: int = Field(ge=1)
    max_candidates: int = Field(ge=1)
    max_search_nodes: int = Field(ge=1)
    reason_codes: tuple[str, ...] = ()
    result_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    claim_boundary: str = (
        "Deterministic conflict/hitting-set reasoning over admitted conflicts. Completeness applies only when "
        "search_complete=true and only to diagnoses within the configured cardinality bound; this is not a "
        "probability, causal proof, or flight-qualified diagnosis."
    )


def _normalize_conflict_sets(conflicts: Sequence[Iterable[str]]) -> list[frozenset[str]]:
    normalized: list[frozenset[str]] = []
    for raw in conflicts:
        item = frozenset(str(v) for v in raw if str(v))
        if not item:
            raise ValueError("model conflict cannot be empty")
        normalized.append(item)
    # A conflict that is a strict superset of another admitted conflict is
    # redundant for hitting-set construction.  Retaining only inclusion-minimal
    # conflicts reduces branching without changing the minimal hitting sets.
    unique = sorted(set(normalized), key=lambda value: (len(value), tuple(sorted(value))))
    minimal: list[frozenset[str]] = []
    for conflict in unique:
        if any(existing.issubset(conflict) for existing in minimal):
            continue
        minimal.append(conflict)
    return minimal


def _minimal_sets(values: Iterable[frozenset[str]]) -> list[frozenset[str]]:
    ordered = sorted(set(values), key=lambda value: (len(value), tuple(sorted(value))))
    result: list[frozenset[str]] = []
    for value in ordered:
        if any(existing.issubset(value) for existing in result):
            continue
        result.append(value)
    return result


def enumerate_minimal_diagnoses(
    conflicts: Sequence[Iterable[str]] | Sequence[ModelConflict],
    *,
    max_cardinality: int = 4,
    max_candidates: int = 128,
    max_search_nodes: int = 100_000,
) -> MinimalDiagnosisResult:
    """Enumerate bounded subset-minimal diagnoses and identify the min-cardinality tier.

    Search is deterministic.  If the node/candidate/cardinality bounds prevent
    complete enumeration, ``search_complete`` is false and a reason code is
    retained; callers must not treat omitted candidates as impossible.
    """
    if max_cardinality < 1 or max_candidates < 1 or max_search_nodes < 1:
        raise ValueError("diagnosis search bounds must be positive")

    models: list[ModelConflict] = []
    if conflicts and isinstance(conflicts[0], ModelConflict):  # type: ignore[index]
        models = list(conflicts)  # type: ignore[arg-type]
        sets = _normalize_conflict_sets([item.fault_ids for item in models])
    else:
        sets = _normalize_conflict_sets(conflicts)  # type: ignore[arg-type]
        models = [
            ModelConflict(
                conflict_id=f"CONFLICT-{index:04d}",
                fault_ids=tuple(sorted(value)),
            )
            for index, value in enumerate(sets)
        ]

    # Ensure the persisted conflict list matches the reduced inclusion-minimal
    # set even when callers supplied redundant ModelConflict objects.
    by_faults = {frozenset(item.fault_ids): item for item in models}
    admitted = tuple(
        by_faults.get(
            value,
            ModelConflict(conflict_id=f"CONFLICT-{index:04d}", fault_ids=tuple(sorted(value))),
        )
        for index, value in enumerate(sets)
    )

    frontier: list[frozenset[str]] = [frozenset()]
    search_nodes = 1
    complete = True
    reasons: set[str] = set()

    for conflict in sets:
        expanded: list[frozenset[str]] = []
        for candidate in frontier:
            if candidate & conflict:
                expanded.append(candidate)
                continue
            for fault_id in sorted(conflict):
                search_nodes += 1
                if search_nodes > max_search_nodes:
                    complete = False
                    reasons.add("SEARCH_NODE_LIMIT_REACHED")
                    break
                new_candidate = candidate | {fault_id}
                if len(new_candidate) <= max_cardinality:
                    expanded.append(new_candidate)
                else:
                    complete = False
                    reasons.add("MAX_CARDINALITY_EXCLUDED_CANDIDATE")
            if search_nodes > max_search_nodes:
                break
        frontier = _minimal_sets(expanded)
        if not frontier or search_nodes > max_search_nodes:
            break

    # Validate discovered candidates against every admitted conflict.  This is
    # kept even though the construction should guarantee it; the explicit check
    # protects future search refactors.
    diagnoses = [candidate for candidate in _minimal_sets(frontier) if all(candidate & c for c in sets)]
    if len(diagnoses) > max_candidates:
        complete = False
        reasons.add("MAX_CANDIDATES_TRUNCATED_OUTPUT")
        diagnoses = diagnoses[:max_candidates]

    min_cardinality = min((len(value) for value in diagnoses), default=None)
    candidates: list[MinimalDiagnosisCandidate] = []
    for value in diagnoses:
        faults = tuple(sorted(value))
        identity = _digest({"fault_ids": faults})
        candidates.append(
            MinimalDiagnosisCandidate(
                diagnosis_id=f"MBD-{identity[:16].upper()}",
                fault_ids=faults,
                cardinality=len(faults),
                minimum_cardinality=(min_cardinality is not None and len(faults) == min_cardinality),
            )
        )
    minimum = tuple(item for item in candidates if item.minimum_cardinality)

    payload = {
        "conflicts": [item.model_dump(mode="json") for item in admitted],
        "subset_minimal_diagnoses": [item.model_dump(mode="json") for item in candidates],
        "minimum_cardinality_diagnoses": [item.model_dump(mode="json") for item in minimum],
        "search_complete": complete,
        "search_nodes": search_nodes,
        "max_cardinality": max_cardinality,
        "max_candidates": max_candidates,
        "max_search_nodes": max_search_nodes,
        "reason_codes": sorted(reasons),
    }
    return MinimalDiagnosisResult(
        conflicts=admitted,
        subset_minimal_diagnoses=tuple(candidates),
        minimum_cardinality_diagnoses=minimum,
        search_complete=complete,
        search_nodes=search_nodes,
        max_cardinality=max_cardinality,
        max_candidates=max_candidates,
        max_search_nodes=max_search_nodes,
        reason_codes=tuple(sorted(reasons)),
        result_sha256=_digest(payload),
    )


__all__ = [
    "ModelConflict",
    "MinimalDiagnosisCandidate",
    "MinimalDiagnosisResult",
    "enumerate_minimal_diagnoses",
]
