class OpenAICompatibleStructuredBackend:
    """OpenAI-compatible structured-output backend for LM Studio/Ollama/vLLM."""

    model_version = "openai-compatible-structured-v4-adaptive-topk"
    supports_diagnostic_deliberation = True
    supports_dynamic_diagnostic_action_schema = True

    def __init__(self, config: OpenAICompatibleConfig, *, tokenizer: Any | None = None) -> None:
        self.config = config
        self.model_id = config.model
        self.last_call_metadata: dict[str, Any] = {}
        self.call_history: list[dict[str, Any]] = []
        self._tokenizer = tokenizer
        self._tokenizer_load_attempted = tokenizer is not None
        self._tokenizer_load_error: str | None = None
        self._last_candidate_selection: dict[str, Any] | None = None

    @property
    def lifecycle_profile(self) -> ProviderLifecycleProfile:
        return BUILTIN_PROVIDER_QUALIFICATIONS.get("http-json-provider.v1")

    @classmethod
    def from_json(cls, path: str | Path) -> "OpenAICompatibleStructuredBackend":
        return cls(OpenAICompatibleConfig.from_json(path))

    def _strategies(self) -> list[str]:
        if self.config.response_format_strategy != "auto":
            return [self.config.response_format_strategy]
        provider = self.config.provider.strip().casefold()
        # LM Studio supports strict JSON Schema, but reasoning-enabled local models can
        # spend the whole request budget inside constrained decoding.  JSON Object mode
        # still receives the exact schema in the prompt and is validated by Pydantic on
        # the host, so prefer the lower-latency compatibility path and keep strict schema
        # as a final fallback.
        if provider in {"lmstudio", "lm-studio"}:
            return ["json_object", "plain_json", "json_schema"]
        return ["json_schema", "json_object", "plain_json"]

    @staticmethod
    def _json_from_text(text: str) -> Any:
        cleaned = text.strip()
        cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned, flags=re.IGNORECASE)
        cleaned = re.sub(r"\s*```$", "", cleaned)
        try:
            return json.loads(cleaned)
        except json.JSONDecodeError:
            pass
        start = cleaned.find("{")
        if start < 0:
            raise StructuredBackendError("model response does not contain a JSON object")
        depth = 0
        in_string = False
        escaped = False
        for index in range(start, len(cleaned)):
            ch = cleaned[index]
            if in_string:
                if escaped:
                    escaped = False
                elif ch == "\\":
                    escaped = True
                elif ch == '"':
                    in_string = False
                continue
            if ch == '"':
                in_string = True
            elif ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    return json.loads(cleaned[start:index + 1])
        raise StructuredBackendError("model response contains an incomplete JSON object")

    @staticmethod
    def _message_content(document: dict[str, Any]) -> tuple[str, str | None]:
        try:
            choice = document["choices"][0]
            content = choice["message"]["content"]
            finish_reason = choice.get("finish_reason")
        except (KeyError, IndexError, TypeError) as exc:
            raise StructuredBackendError(f"invalid OpenAI-compatible response shape: {document}") from exc
        if isinstance(content, str):
            return content, finish_reason
        if isinstance(content, list):
            parts: list[str] = []
            for item in content:
                if isinstance(item, dict) and isinstance(item.get("text"), str):
                    parts.append(item["text"])
            if parts:
                return "".join(parts), finish_reason
        raise StructuredBackendError("chat completion content is not text")

    @staticmethod
    def _request_id(body: dict[str, Any]) -> str:
        wire = json.dumps(
            body, ensure_ascii=False, sort_keys=True, separators=(",", ":"), default=str,
        ).encode("utf-8")
        return "astrograph-" + hashlib.sha256(wire).hexdigest()[:32]

    def _post(self, body: dict[str, Any]) -> dict[str, Any]:
        from astrograph.integrations.bounded_http import request_json
        from .audit import current_audit
        audit=current_audit()
        return request_json(self.config.chat_completions_url, payload=body,
            headers={
                "Authorization": f"Bearer {self.config.api_key.get_secret_value()}",
                "X-Request-Id": self._request_id(body),
            },
            timeout_s=self.config.timeout_s, max_response_bytes=self.config.max_response_bytes,
            response_observer=audit.response if audit else None)

    @staticmethod
    def _reference_items(payload: dict[str, Any]) -> list[dict[str, Any]]:
        reference = payload.get("reference_hypothesis_set")
        if not isinstance(reference, dict):
            return []
        return [item for item in reference.get("hypotheses", []) if isinstance(item, dict)]

    def _select_compact_fault_ids(self, payload: dict[str, Any]) -> list[str]:
        candidate_fusion = payload.get("candidate_fusion")
        if isinstance(candidate_fusion, dict):
            from astrograph.fusion import CandidateFusionPackage, select_fused_candidates

            package = CandidateFusionPackage.model_validate(candidate_fusion)
            result, snapshot = select_fused_candidates(
                package,
                self._reference_items(payload),
                mode=self.config.candidate_top_k_mode,
                configured_top_k=self.config.candidate_top_k,
                min_top_k=self.config.candidate_top_k_min,
                max_top_k=self.config.candidate_top_k_max,
            )
            self._last_candidate_selection = snapshot
            return result.selected_fault_ids

        registered_fault_ids = [str(value) for value in payload.get("registered_fault_ids", [])]
        request = selection_input_from_reference(
            self._reference_items(payload),
            registered_fault_ids=registered_fault_ids,
            top_k=self.config.candidate_top_k,
        )
        effective_top_k = resolve_candidate_top_k(
            request.candidates,
            mode=self.config.candidate_top_k_mode,
            configured_top_k=self.config.candidate_top_k,
            min_top_k=self.config.candidate_top_k_min,
            max_top_k=self.config.candidate_top_k_max,
        )
        if effective_top_k != request.top_k:
            request = request.model_copy(update={"top_k": effective_top_k})
        result = select_candidates(request)
        selection_snapshot = result.model_dump(mode="json")
        selection_snapshot.update({
            "selection_source": "REFERENCE_HYPOTHESIS_SET",
            "top_k_mode": self.config.candidate_top_k_mode,
            "configured_top_k": self.config.candidate_top_k,
            "effective_top_k": effective_top_k,
            "candidate_top_k_min": self.config.candidate_top_k_min,
            "candidate_top_k_max": self.config.candidate_top_k_max,
        })
        self._last_candidate_selection = selection_snapshot
        return result.selected_fault_ids

    def _prepare_effective_payload(self, payload: dict[str, Any]) -> tuple[dict[str, Any], list[str], bool]:
        effective = dict(payload)
        selected: list[str] = []
        compact_applied = False
        if self.config.compact_reasoning and isinstance(payload.get("reference_hypothesis_set"), dict):
            selected = self._select_compact_fault_ids(payload)
            selection = self._last_candidate_selection or {}
            compact_allowed = bool(selection.get("compact_reasoning_allowed", True))
            if not compact_allowed:
                effective["candidate_selection_escape"] = {
                    "candidate_set_status": selection.get("candidate_set_status"),
                    "escape_action": selection.get("escape_action"),
                    "escape_reason_codes": selection.get("escape_reason_codes", []),
                    "unselected_mandatory_fault_ids": selection.get("unselected_mandatory_fault_ids", []),
                    "preferred_candidate_fault_ids": selected,
                    "instruction": (
                        "Compact Top-K filtering was disabled by deterministic runtime policy. "
                        "Use the full registered candidate/evidence context and do not infer that the preferred list is exhaustive."
                    ),
                }
            else:
                compact_applied = True
                selected_set = set(selected)
                definitions = [
                    item for item in payload.get("evidence_definitions", [])
                    if item.get("target_fault_id") in selected_set
                ]
                definition_ids = {item.get("evidence_definition_id") for item in definitions}
                facts = [
                    item for item in payload.get("evidence_facts", [])
                    if item.get("evidence_definition_id") in definition_ids
                ]
                protocol = dict(payload.get("diagnostic_protocol", {}))
                protocol["faults"] = {
                    key: value for key, value in protocol.get("faults", {}).items() if key in selected_set
                }
                effective.update(
                    {
                        "registered_fault_ids": selected,
                        "selected_candidate_fault_ids": selected,
                        "evidence_definitions": definitions,
                        "evidence_facts": facts,
                        "diagnostic_protocol": protocol,
                        "allowed_evidence_fact_ids": sorted(
                            item.get("evidence_fact_id") for item in facts if item.get("evidence_fact_id")
                        ),
                        "allowed_evidence_definition_ids": sorted(
                            item.get("evidence_definition_id") for item in definitions if item.get("evidence_definition_id")
                        ),
                        "compact_protocol": {
                            "schema_version": "astrograph-compact-reasoner-proposal.v1",
                            "instruction": (
                                "Only return proposals for selected_candidate_fault_ids. Do not return "
                                "CONTRADICTED non-candidates or NO_REGISTERED_FAULT; AstroGraph compiles them deterministically."
                            ),
                        },
                    }
                )
                if isinstance(payload.get("reference_hypothesis_set"), dict):
                    compact_reference = dict(payload["reference_hypothesis_set"])
                    compact_reference["hypotheses"] = [
                        item for item in payload["reference_hypothesis_set"].get("hypotheses", [])
                        if item.get("target_fault_id") in selected_set
                    ]
                    effective["reference_hypothesis_set"] = compact_reference
                # V0.5.10 compact trimming: the fused candidate package is the largest prompt section
                # (~25k chars for all 16 registered faults) and is unfiltered by the compact protocol.
                # The compact instruction tells the model to reason only about selected candidates and that
                # non-candidates are compiled deterministically, so drop non-selected fused candidates too.
                # This keeps prompt + output within small-context backends (e.g. vLLM 16384-token limit).
                candidate_fusion = payload.get("candidate_fusion")
                if isinstance(candidate_fusion, dict):
                    effective["candidate_fusion"] = self._compact_candidate_fusion(candidate_fusion, selected_set)
                retrieval = payload.get("pre_reasoning_retrieval")
                if isinstance(retrieval, dict):
                    compact_retrieval = self._compact_pre_reasoning_retrieval(retrieval, selected_set)
                    effective["pre_reasoning_retrieval"] = compact_retrieval
                    effective["allowed_retrieval_source_ids"] = sorted({
                        str(item.get("source_id"))
                        for item in compact_retrieval.get("local_hits", [])
                        if item.get("source_id")
                    })
        if not self.config.include_reference_hypothesis_set:
            effective.pop("reference_hypothesis_set", None)
        return effective, selected, compact_applied

    @staticmethod
    def _compact_candidate_fusion(fusion: dict[str, Any], selected: set[str]) -> dict[str, Any]:
        """Filter a CandidateFusionPackage dict down to the compact-selected fault IDs.

        The full package serialises all 16 registered faults with per-fault source scores and
        evidence lists, which dominates the compact prompt budget. The compact protocol only asks
        the model to reason about ``selected`` candidates; the remaining hypotheses are compiled
        deterministically, so their fused candidates add no signal for the model.
        """
        if not isinstance(fusion, dict):
            return fusion

        def keep_candidates(ranking: Any) -> Any:
            if isinstance(ranking, dict):
                candidates = []
                for item in ranking.get("candidates", []):
                    if item.get("fault_id") not in selected:
                        continue
                    # Provider metadata and correlation-group inventories can contain
                    # window-sized lineage (hundreds of KB). Candidate selection has
                    # already consumed them deterministically; the LLM needs only the
                    # bounded rank/score and evidence anchors below.
                    candidates.append({
                        key: item[key]
                        for key in (
                            "fault_id", "rank", "score", "source", "evidence_fact_ids",
                            "source_evidence_ids", "lineage_complete", "contributes_to_fusion",
                        )
                        if key in item
                    })
                return {
                    key: value
                    for key, value in ranking.items()
                    if key not in {"candidates", "metadata", "kg_fault_coverage"}
                } | {"candidates": candidates}
            return ranking

        compact = dict(fusion)
        for key in ("data_ranking", "forward_ranking", "backward_ranking"):
            compact[key] = keep_candidates(fusion.get(key))
        birrf = fusion.get("birrf_result")
        if isinstance(birrf, dict):
            birrf_candidates = [
                {
                    key: item[key]
                    for key in (
                        "fault_id", "final_rank", "fused_score", "source_ranks", "source_scores",
                        "supporting_evidence_fact_ids", "reciprocal_contributions",
                    )
                    if key in item
                }
                for item in birrf.get("candidates", [])
                if item.get("fault_id") in selected
            ]
            compact["birrf_result"] = {
                key: birrf[key]
                for key in (
                    "fusion_id", "episode_id", "top_fault_id", "conflict_flags",
                    "blocking_conflicts", "quality_warnings", "open_set_actions",
                )
                if key in birrf
            } | {"candidates": birrf_candidates}
        compact.pop("metadata", None)
        compact["registered_fault_ids"] = sorted(selected)
        return compact

    @staticmethod
    def _compact_pre_reasoning_retrieval(
        retrieval: dict[str, Any], selected: set[str]
    ) -> dict[str, Any]:
        """Keep cited candidate/experience context without prompt-only audit bulk."""
        selected_concepts = {f"fault:{fault_id}" for fault_id in selected}
        selected_concepts.update(map(str, retrieval.get("ontology_seed_concept_ids", [])))
        linked_chunk_ids = {
            str(item.get("retrieval_chunk_id"))
            for item in retrieval.get("document_graph_trace_links", [])
            if item.get("retrieval_chunk_id") is not None
        }
        hits = []
        for item in retrieval.get("local_hits", []):
            matched = set(map(str, item.get("matched_concept_ids", [])))
            if not (matched & selected_concepts) and str(item.get("chunk_id")) not in linked_chunk_ids:
                continue
            hits.append({
                key: (str(item[key])[:320] if key == "snippet" else item[key])
                for key in (
                    "chunk_id", "source_id", "source_uri", "source_sha256", "chunk_sha256",
                    "knowledge_version", "rank", "score", "matched_concept_ids", "snippet", "lane",
                )
                if key in item
            })
        paths = [
            item for item in retrieval.get("ontology_paths", [])
            if item.get("seed_concept_id") in selected_concepts
            or item.get("target_concept_id") in selected_concepts
        ]
        compact_hit_ids = {str(item["chunk_id"]) for item in hits}
        trace_links = [
            item for item in retrieval.get("document_graph_trace_links", [])
            if str(item.get("retrieval_chunk_id")) in compact_hit_ids
        ]
        return {
            key: retrieval[key]
            for key in (
                "schema_version", "package_id", "query_id", "episode_id", "status",
                "matched_concept_ids", "required_concept_coverage", "reason_codes",
                "query_construction_mode", "grounding_fault_ids", "grounding_evidence_fact_ids",
                "experience_hit_count", "experience_source_ids", "experience_reuse_receipt",
                "ontology_seed_concept_ids", "ontology_asset_audits",
                "knowledge_update_candidates", "active_graph_modified", "claim_boundary",
                "document_evidence_claims", "document_claim_admissions",
            )
            if key in retrieval
        } | {
            "local_hits": hits,
            "ontology_paths": paths,
            "document_graph_trace_links": trace_links,
        }

    def _estimate_output_tokens(self, *, hypothesis_count: int) -> int:
        raw = self.config.output_budget_base_tokens + (
            hypothesis_count * self.config.output_budget_tokens_per_candidate
        )
        return max(128, math.ceil(raw * self.config.output_budget_safety_margin))

    def _load_tokenizer(self) -> Any | None:
        if self.config.tokenizer_mode == "disabled":
            return None
        if self._tokenizer_load_attempted:
            return self._tokenizer
        self._tokenizer_load_attempted = True
        path = resolve_tokenizer_path(self.config.tokenizer_path, self.config.model)
        if path is None:
            self._tokenizer_load_error = "tokenizer_path is not configured and model is not a local path"
            return None
        try:
            self._tokenizer = load_huggingface_tokenizer(
                path,
                local_files_only=self.config.tokenizer_local_files_only,
                trust_remote_code=self.config.tokenizer_trust_remote_code,
            )
        except TokenizerLoadError as exc:
            self._tokenizer_load_error = str(exc)
            self._tokenizer = None
        return self._tokenizer

    def _measure_prompt_tokens(
        self,
        *,
        payload: dict[str, Any],
        messages: list[dict[str, str]],
    ) -> dict[str, Any]:
        old_rough = rough_token_estimate(payload)
        message_rough = rough_token_estimate(messages)
        tokenizer_count: int | None = None
        tokenizer_error: str | None = None
        tokenizer = self._load_tokenizer()
        if tokenizer is not None:
            try:
                tokenizer_count = count_chat_tokens(tokenizer, messages)
            except TokenizerLoadError as exc:
                tokenizer_error = str(exc)
        elif self._tokenizer_load_error:
            tokenizer_error = self._tokenizer_load_error
        if self.config.tokenizer_mode == "required" and tokenizer_count is None:
            raise TokenizerLoadError(tokenizer_error or "required tokenizer is unavailable")
        selected = tokenizer_count if tokenizer_count is not None else message_rough
        method = "tokenizer_chat_template" if tokenizer_count is not None else "rough_messages_chars_per_3_5"
        if tokenizer_count is None and payload.get("work_mode") in {"normal","thinking","creative"}:
            # HTTP JSON escaping is transport, not model-visible prompt text.
            # Count actual role/content bytes plus an explicit framing allowance.
            # This remains a conservative estimate, NOT a verified tokenizer count.
            selected=sum(len(m.get("content", "").encode("utf-8")) + len(m.get("role", "").encode("utf-8")) for m in messages) + 512
            method="mission_utf8_content_bytes_plus_512_frame_reserve_not_exact_tokenizer"
        guarded = math.ceil(selected * self.config.prompt_token_safety_margin) + self.config.prompt_token_reserve
        return {
            "estimator_schema_version": "astrograph-prompt-token-measurement.v2",
            "method": method,
            "rough_payload_estimated_prompt_tokens": old_rough,
            "rough_messages_estimated_prompt_tokens": message_rough,
            "tokenizer_prompt_tokens": tokenizer_count,
            "selected_prompt_tokens": selected,
            "prompt_token_safety_margin": self.config.prompt_token_safety_margin,
            "prompt_token_reserve": self.config.prompt_token_reserve,
            "guarded_prompt_tokens": guarded,
            "rough_payload_relative_error_vs_tokenizer": relative_error(old_rough, tokenizer_count),
            "rough_messages_relative_error_vs_tokenizer": relative_error(message_rough, tokenizer_count),
            "tokenizer_error": tokenizer_error,
        }

    def measure_structured_context(self, *, output_model: type[BaseModel], payload: dict[str, Any]) -> dict[str, Any]:
        """Preview the SAME chat/schema/output budget used by generation, without HTTP.

        Context projection must not reject tokenized text using a separate byte
        budget. A missing required tokenizer is still a hard configuration error.
        """
        messages = self._messages(output_model=output_model, payload=payload)
        count = 1  # Mission schemas follow the non-reasoner path in generate_structured.
        try:
            budget = self._budget(payload=payload, messages=messages, request_hypothesis_count=count)
        except OutputBudgetError as exc:
            return {"fits": False, "reason": str(exc), **exc.budget}
        return {"fits": True, **budget}

    def _budget(
        self,
        *,
        payload: dict[str, Any],
        messages: list[dict[str, str]],
        request_hypothesis_count: int,
    ) -> dict[str, Any]:
        required = self._estimate_output_tokens(hypothesis_count=request_hypothesis_count)
        effective = self.config.max_tokens
        auto_expanded = False
        measurement = self._measure_prompt_tokens(payload=payload, messages=messages)
        budget = {
            "configured_max_tokens": self.config.max_tokens,
            "required_output_tokens": required,
            "effective_max_tokens": effective,
            "auto_expanded": auto_expanded,
            "estimated_prompt_tokens": measurement["selected_prompt_tokens"],
            "guarded_prompt_tokens": measurement["guarded_prompt_tokens"],
            "configured_context_length": self.config.context_length,
            "prompt_token_measurement": measurement,
        }
        if self.config.budget_preflight and effective < required:
            if self.config.budget_policy == "auto_expand" and required <= self.config.max_tokens_ceiling:
                effective = required
                auto_expanded = True
                budget["effective_max_tokens"] = effective
                budget["auto_expanded"] = True
            else:
                raise OutputBudgetError(
                    "configured max_tokens is below the AstroGraph structured-output budget: "
                    f"configured={self.config.max_tokens}, required={required}, "
                    f"candidate_count={request_hypothesis_count}. Use compact profile or increase max_tokens.",
                    budget=budget,
                )
        guarded = int(measurement["guarded_prompt_tokens"])
        if self.config.context_length is not None and guarded + effective > self.config.context_length:
            raise OutputBudgetError(
                "measured prompt+output exceeds configured context_length: "
                f"method={measurement['method']}, prompt={guarded}, output={effective}, "
                f"context={self.config.context_length}",
                budget=budget,
            )
        return budget

    @staticmethod
    def _attach_server_usage(budget: dict[str, Any], response: dict[str, Any]) -> dict[str, Any]:
        enriched = json.loads(json.dumps(budget, ensure_ascii=False, default=str))
        usage = response.get("usage")
        if not isinstance(usage, dict):
            return enriched
        prompt_actual = usage.get("prompt_tokens")
        completion_actual = usage.get("completion_tokens")
        total_actual = usage.get("total_tokens")
        measurement = enriched.get("prompt_token_measurement", {})
        measurement["server_prompt_tokens"] = prompt_actual
        measurement["server_completion_tokens"] = completion_actual
        measurement["server_total_tokens"] = total_actual
        measurement["tokenizer_relative_error_vs_server"] = relative_error(
            measurement.get("tokenizer_prompt_tokens"), prompt_actual
        )
        measurement["rough_payload_relative_error_vs_server"] = relative_error(
            measurement.get("rough_payload_estimated_prompt_tokens"), prompt_actual
        )
        measurement["rough_messages_relative_error_vs_server"] = relative_error(
            measurement.get("rough_messages_estimated_prompt_tokens"), prompt_actual
        )
        enriched["prompt_token_measurement"] = measurement
        enriched["server_usage"] = {
            "prompt_tokens": prompt_actual,
            "completion_tokens": completion_actual,
            "total_tokens": total_actual,
        }
        return enriched

