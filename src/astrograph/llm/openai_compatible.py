    def _body(
        self,
        *,
        output_model: type[BaseModel],
        payload: dict[str, Any],
        strategy: str,
        max_tokens: int,
        repair_note: str | None = None,
    ) -> dict[str, Any]:
        from .task_prompts import task_output_schema
        schema = task_output_schema(output_model,payload)
        body: dict[str, Any] = {
            "model": self.config.model,
            "messages": self._messages(
                output_model=output_model,
                payload=payload,
                repair_note=repair_note,
            ),
            "temperature": self.config.temperature,
            "max_tokens": max_tokens,
            "stream": False,
        }
        if self.config.seed is not None:
            body["seed"] = self.config.seed
        if strategy == "json_schema":
            body["response_format"] = {
                "type": "json_schema",
                "json_schema": {
                    "name": output_model.__name__,
                    "strict": True,
                    "schema": schema,
                },
            }
        elif strategy == "json_object":
            body["response_format"] = {"type": "json_object"}
        return body

    @staticmethod
    def _compile_full_reasoner_proposals(
        proposals: _ReasonerProposalSet,
        *,
        payload: dict[str, Any],
        output_model: type[T],
    ) -> T:
        reference = payload.get("reference_hypothesis_set")
        if not isinstance(reference, dict):
            raise StructuredBackendError("reasoner proposal compilation requires a local reference envelope")
        base_by_key = {
            (str(item.get("hypothesis_type")), item.get("target_fault_id")): item
            for item in reference.get("hypotheses", [])
        }
        proposal_by_key = {
            (item.hypothesis_type, item.target_fault_id): item for item in proposals.hypotheses
        }
        if len(proposal_by_key) != len(proposals.hypotheses):
            raise StructuredBackendError("model returned duplicate hypothesis keys")
        required_keys = set(base_by_key)
        returned_keys = set(proposal_by_key)
        if returned_keys != required_keys:
            raise StructuredBackendError(
                f"model must return all hypotheses; missing={sorted(required_keys-returned_keys, key=str)}, "
                f"extra={sorted(returned_keys-required_keys, key=str)}"
            )
        compiled = dict(reference)
        compiled["hypotheses"] = []
        for key, base in base_by_key.items():
            item = dict(base)
            item.update(proposal_by_key[key].model_dump(mode="json"))
            compiled["hypotheses"].append(item)
        metadata = dict(compiled.get("validation_metadata", {}))
        metadata.update({"proposal_protocol": "full-v1", "llm_proposal_count": len(proposals.hypotheses)})
        compiled["validation_metadata"] = metadata
        return output_model.model_validate(compiled)

    @staticmethod
    def _compile_compact_reasoner_proposals(
        proposals: _CompactReasonerProposalSet,
        *,
        payload: dict[str, Any],
        selected_fault_ids: list[str],
        output_model: type[T],
        budget: dict[str, Any],
    ) -> T:
        reference = payload.get("reference_hypothesis_set")
        if not isinstance(reference, dict):
            raise StructuredBackendError("compact proposal compilation requires a local reference envelope")
        selected = set(selected_fault_ids)
        proposal_by_fault: dict[str, _ReasonerHypothesisProposal] = {}
        for proposal in proposals.hypotheses:
            if proposal.hypothesis_type != "REGISTERED_FAULT" or not proposal.target_fault_id:
                raise StructuredBackendError("compact output only accepts REGISTERED_FAULT proposals")
            if proposal.target_fault_id not in selected:
                raise StructuredBackendError(
                    f"model returned non-selected fault in compact output: {proposal.target_fault_id}"
                )
            if proposal.target_fault_id in proposal_by_fault:
                raise StructuredBackendError("model returned duplicate compact fault proposal")
            proposal_by_fault[proposal.target_fault_id] = proposal
        missing_selected = selected - set(proposal_by_fault)
        if missing_selected and payload.get("capture_shadow_candidate_revision") is not True:
            raise StructuredBackendError(
                f"compact model must return exactly selected candidates; missing={sorted(selected-set(proposal_by_fault))}, "
                f"extra={sorted(set(proposal_by_fault)-selected)}"
            )
        compiled = dict(reference)
        compiled_items: list[dict[str, Any]] = []
        replaced = 0
        for base in reference.get("hypotheses", []):
            item = dict(base)
            fault_id = item.get("target_fault_id")
            if item.get("hypothesis_type") == "REGISTERED_FAULT" and fault_id in proposal_by_fault:
                item.update(proposal_by_fault[str(fault_id)].model_dump(mode="json"))
                replaced += 1
            compiled_items.append(item)
        compiled["hypotheses"] = compiled_items
        metadata = dict(compiled.get("validation_metadata", {}))
        metadata.update(
            {
                "proposal_protocol": "compact-v1",
                "selected_candidate_fault_ids": selected_fault_ids,
                "llm_proposal_count": replaced,
                "deterministically_completed_hypothesis_count": len(compiled_items) - replaced,
                **({
                    "exploratory_missing_compact_candidate_fault_ids": sorted(missing_selected),
                    "exploratory_compact_proposal_degraded": True,
                } if missing_selected else {}),
                "output_budget": budget,
            }
        )
        compiled["validation_metadata"] = metadata
        return output_model.model_validate(compiled)

    def generate_structured(self, *, agent_id: str, output_model: type[T], payload: dict[str, Any]) -> T:
        from astrograph.integrations.execution_budget import current_budget, ExecutionBudget, execution_scope, interruptible_timeout
        if current_budget() is None:
            with execution_scope(ExecutionBudget(self.config.timeout_s,self.config.max_http_attempts)):
                with interruptible_timeout(self.config.timeout_s,"LLM_TOTAL_DEADLINE_EXCEEDED"):
                    return self._generate_structured_impl(agent_id=agent_id,output_model=output_model,payload=payload)
        with interruptible_timeout(self.config.timeout_s,"LLM_TOTAL_DEADLINE_EXCEEDED"):
            return self._generate_structured_impl(agent_id=agent_id,output_model=output_model,payload=payload)

    def _generate_structured_impl(
        self,
        *,
        agent_id: str,
        output_model: type[T],
        payload: dict[str, Any],
    ) -> T:
        started = time.perf_counter()
        reasoner_request = output_model.__name__ == "HypothesisSet" and isinstance(
            payload.get("reference_hypothesis_set"), dict
        )
        shadow_requested = reasoner_request and payload.get("capture_shadow_candidate_revision") is True
        effective_payload, selected_fault_ids, compact_applied = self._prepare_effective_payload(payload)
        compact_requested = reasoner_request and self.config.compact_reasoning
        compact = compact_requested and compact_applied
        candidate_escape_applied = compact_requested and not compact_applied and bool(self._last_candidate_selection)
        if compact:
            request_model: type[BaseModel] = (
                _CompactReasonerProposalSetWithShadow if shadow_requested else _CompactReasonerProposalSet
            )
            request_hypothesis_count = len(selected_fault_ids)
        elif reasoner_request:
            request_model = _ReasonerProposalSetWithShadow if shadow_requested else _ReasonerProposalSet
            request_hypothesis_count = len(self._reference_items(payload))
        else:
            request_model = output_model
            request_hypothesis_count = 1

        errors: list[str] = []
        attempts = 0
        request_ids: list[str] = []
        finish_reasons: list[str | None] = []
        prompt_hash = hashlib.sha256(
            json.dumps(effective_payload, ensure_ascii=False, sort_keys=True, default=str).encode("utf-8")
        ).hexdigest()
        initial_messages = self._messages(
            output_model=request_model,
            payload=effective_payload,
        )
        try:
            budget = self._budget(
                payload=effective_payload,
                messages=initial_messages,
                request_hypothesis_count=request_hypothesis_count,
            )
        except Exception as exc:
            self.last_call_metadata = {
                "agent_id": agent_id,
                "model_id": self.model_id,
                "status": "BUDGET_REJECTED",
                "error": f"{type(exc).__name__}: {exc}",
                "prompt_profile": self.config.prompt_profile,
                "selected_candidate_fault_ids": selected_fault_ids,
                "candidate_selection": self._last_candidate_selection,
                "candidate_escape_applied": candidate_escape_applied,
                "runtime_snapshot": self.config.public_snapshot(),
                "output_budget": getattr(exc, "budget", {}),
            }
            self.call_history.append(dict(self.last_call_metadata))
            raise

        from astrograph.integrations.execution_budget import current_budget, AttemptBudgetExceeded, ExecutionDeadlineExceeded
        effective_max_tokens = int(budget["effective_max_tokens"])
        for strategy in self._strategies():
            repair_note: str | None = None
            current_max_tokens = effective_max_tokens
            for repair_index in range(self.config.repair_attempts + 1):
                try:
                    body = self._body(
                            output_model=request_model,
                            payload=effective_payload,
                            strategy=strategy,
                            max_tokens=current_max_tokens,
                            repair_note=repair_note,
                        )
                    measurement = self._measure_prompt_tokens(payload=effective_payload, messages=body["messages"])
                    if self.config.context_length is not None and measurement["guarded_prompt_tokens"] + current_max_tokens > self.config.context_length:
                        raise OutputBudgetError("RETRY_CONTEXT_BUDGET_EXCEEDED", budget={**budget,"retry_measurement":measurement,"effective_max_tokens":current_max_tokens})
                    if attempts >= self.config.max_http_attempts:
                        raise AttemptBudgetExceeded("LLM_PROVIDER_ATTEMPT_BUDGET_EXHAUSTED")
                    task_budget = current_budget()
                    if task_budget is not None:
                        task_budget.consume_http(self.model_id, strategy)
                    attempts += 1
                    request_id = self._request_id(body)
                    request_ids.append(request_id)
                    from .audit import current_audit, wire_bytes
                    audit=current_audit()
                    if audit:audit.request(body)
                    try:
                        response = self._post(body)
                    except Exception as transport_error:
                        if audit:audit.complete(error=transport_error)
                        raise
                    if audit:audit.complete(document=response)
                    content, finish_reason = self._message_content(response)
                    observed_budget = self._attach_server_usage(budget, response)
                    finish_reasons.append(finish_reason)
                    if self.config.detect_finish_reason_length and finish_reason in {"length", "max_tokens"}:
                        raise OutputTruncatedError(
                            f"model reported finish_reason={finish_reason}; response_chars={len(content)}"
                        )
                    parsed = self._json_from_text(content)
                    if shadow_requested and isinstance(parsed, dict) and "shadow_candidate_revision" not in parsed:
                        # A missing optional research suggestion must not destroy
                        # otherwise valid formal hypotheses; the host records it unavailable.
                        parsed = {**parsed, "shadow_candidate_revision": None}
                    parsed_result = request_model.model_validate(parsed)
                    if compact:
                        result = self._compile_compact_reasoner_proposals(
                            parsed_result,
                            payload=payload,
                            selected_fault_ids=selected_fault_ids,
                            output_model=output_model,
                            budget=observed_budget,
                        )
                    elif reasoner_request:
                        result = self._compile_full_reasoner_proposals(
                            parsed_result,
                            payload=payload,
                            output_model=output_model,
                        )
                    else:
                        result = parsed_result
                    self.last_call_metadata = {
                        "agent_id": agent_id,
                        "model_id": self.model_id,
                        "strategy": strategy,
                        "attempts": attempts,
                        "request_id": request_id,
                        "request_ids": list(request_ids),
                        "latency_s": round(time.perf_counter() - started, 6),
                        "prompt_sha256": prompt_hash,
                        "actual_request_sha256":hashlib.sha256(wire_bytes(body)).hexdigest(),
                        "response_chars": len(content),
                        "finish_reason": finish_reason,
                        "finish_reasons": finish_reasons,
                        "reference_included": self.config.include_reference_hypothesis_set,
                        "prompt_profile": self.config.prompt_profile,
                        "compiled_from_proposal": reasoner_request,
                        "compact_protocol": compact,
                        "candidate_escape_applied": candidate_escape_applied,
                        "selected_candidate_fault_ids": selected_fault_ids,
                        **({
                            "shadow_candidate_revision_proposal": parsed_result.shadow_candidate_revision,
                            "shadow_candidate_revision_requested": True,
                        } if shadow_requested else {}),
                        "candidate_selection": self._last_candidate_selection,
                        "output_budget": observed_budget,
                        "runtime_snapshot": self.config.public_snapshot(
                            effective_max_tokens=current_max_tokens
                        ),
                        "status": "SUCCEEDED",
                    }
                    self.call_history.append(dict(self.last_call_metadata))
                    return result
                except Exception as exc:
                    message = f"{strategy}/attempt-{repair_index + 1}: {type(exc).__name__}: {exc}"
                    errors.append(message)
                    if isinstance(exc, (AttemptBudgetExceeded, ExecutionDeadlineExceeded, OutputBudgetError)):
                        self.last_call_metadata = {"status":"BUDGET_REJECTED", "attempts":attempts,"errors":errors,"output_budget":getattr(exc,"budget",{})}
                        self.call_history.append(dict(self.last_call_metadata))
                        raise
                    if isinstance(exc, OutputTruncatedError) and self.config.budget_policy == "auto_expand":
                        expanded = min(
                            self.config.max_tokens_ceiling,
                            max(current_max_tokens * 2, int(budget["required_output_tokens"])),
                        )
                        if expanded > current_max_tokens:
                            current_max_tokens = expanded
                            repair_note = (
                                "The previous response was truncated by the output-token limit. Return a fresh complete "
                                "JSON object using the compact schema. Do not continue prose from the previous response."
                            )
                            continue
                    repair_note = (
                        "The previous output failed parsing or schema validation. Return only a corrected JSON object. "
                        f"Validation error: {str(exc)[:1200]}"
                    )
        self.last_call_metadata = {
            "agent_id": agent_id,
            "model_id": self.model_id,
            "attempts": attempts,
            "request_ids": list(request_ids),
            "latency_s": round(time.perf_counter() - started, 6),
            "prompt_sha256": prompt_hash,
            "finish_reasons": finish_reasons,
            "reference_included": self.config.include_reference_hypothesis_set,
            "prompt_profile": self.config.prompt_profile,
            "compiled_from_proposal": reasoner_request,
            "compact_protocol": compact,
            "candidate_escape_applied": candidate_escape_applied,
            "selected_candidate_fault_ids": selected_fault_ids,
            "candidate_selection": self._last_candidate_selection,
            "output_budget": budget,
            "runtime_snapshot": self.config.public_snapshot(
                effective_max_tokens=effective_max_tokens
            ),
            "status": "FAILED",
            "errors": errors,
        }
        self.call_history.append(dict(self.last_call_metadata))
        raise StructuredBackendError("structured generation failed: " + " | ".join(errors[-6:]))
