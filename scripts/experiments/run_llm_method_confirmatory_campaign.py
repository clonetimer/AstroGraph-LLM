#!/usr/bin/env python3
"""Run the frozen 38-case A0-A7 confirmatory campaign only after fail-closed admission."""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from astrograph.evaluation.confirmatory_runtime_identity import (
    acquire_model_runtime_attestation,
    build_confirmatory_runtime_identity_admission,
    load_confirmatory_python_environment_lock,
    verify_confirmatory_runtime_identity_drift,
)
from astrograph.evaluation.llm_method_campaign import (
    build_confirmatory_execution_receipt,
    confirmatory_readiness,
    evaluate_confirmatory_promotion,
    load_confirmatory_design,
    verify_confirmatory_dataset_snapshot_receipt,
    verify_confirmatory_execution_identity,
)


def _write(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _probe_models(url: str) -> tuple[list[str], str, bool]:
    endpoint = url.rstrip("/") + "/models"
    try:
        with urllib.request.urlopen(endpoint, timeout=3.0) as response:
            payload = json.loads(response.read().decode("utf-8"))
        models = sorted(str(item.get("id")) for item in payload.get("data", []) if item.get("id"))
        return models, "models=" + ",".join(models), True
    except Exception as exc:
        return [], f"{type(exc).__name__}:{exc}", False


def _runtime_attestation_source(args: argparse.Namespace) -> dict[str, str | None]:
    return {
        "model_runtime_spec": str(args.model_runtime_spec.resolve()) if args.model_runtime_spec else None,
        "model_runtime_attestation_url": args.model_runtime_attestation_url,
    }


def _acquire_runtime_identity(
    *,
    args: argparse.Namespace,
    environment_lock: dict,
) -> tuple[dict | None, dict, dict]:
    attestation, source = acquire_model_runtime_attestation(
        spec_path=(args.model_runtime_spec.resolve() if args.model_runtime_spec else None),
        attestation_url=args.model_runtime_attestation_url,
    )
    admission = build_confirmatory_runtime_identity_admission(
        ROOT,
        environment_lock=environment_lock,
        model_runtime_attestation=attestation,
        vllm_url=args.vllm_url,
        vllm_model=args.vllm_model,
    )
    source = dict(source)
    source.update(_runtime_attestation_source(args))
    return attestation, source, admission


def _merge_identity_checks(*checks: dict) -> dict:
    drift_codes: list[str] = []
    details: list[dict] = []
    for check in checks:
        details.append(check)
        if check.get("status") != "STABLE":
            drift_codes.extend(str(item) for item in (check.get("drift_codes") or []))
    return {
        "schema_version": "astrograph-llm-method-confirmatory-combined-identity-check.v1",
        "status": "STABLE" if not drift_codes else "DRIFTED",
        "drift_codes": sorted(set(drift_codes)),
        "checks": details,
        "claim_boundary": (
            "Combined post-execution dataset/source/environment/model-runtime identity check. "
            "STABLE is a reproducibility identity result only, not a model-performance or flight-qualification result."
        ),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--vllm-url", default="http://127.0.0.1:8000/v1")
    parser.add_argument("--vllm-model", default="Qwen3.5-9B")
    parser.add_argument("--adcs-root", type=Path)
    parser.add_argument("--phm-root", type=Path)
    parser.add_argument("--case-manifest", type=Path, help="Explicit frozen case manifest; may live outside the source tree.")
    parser.add_argument(
        "--dataset-snapshot-receipt", type=Path, required=True,
        help="Content-addressed snapshot receipt generated by the confirmatory preparation command.",
    )
    parser.add_argument(
        "--environment-lock", type=Path, required=True,
        help="Frozen exact AstroGraph orchestrator Python environment lock produced before confirmatory execution.",
    )
    identity_source = parser.add_mutually_exclusive_group(required=True)
    identity_source.add_argument(
        "--model-runtime-spec", type=Path,
        help="Local/sidecar model-runtime spec. Model/tokenizer/server bytes are rehashed before and after the campaign.",
    )
    identity_source.add_argument(
        "--model-runtime-attestation-url",
        help="HTTP endpoint returning a freshly recomputed model-runtime attestation. Producer authentication remains external to R16.",
    )
    parser.add_argument("--require-readonly-datasets", action="store_true")
    parser.add_argument("--dry-run", action="store_true", help="Admission + receipt only; do not execute A0-A7.")
    args = parser.parse_args()

    output_dir = args.output_dir.resolve()
    if output_dir == ROOT or ROOT in output_dir.parents:
        parser.error("--output-dir must be outside the immutable AstroGraph source tree")
    output_dir.mkdir(parents=True, exist_ok=True)

    design = load_confirmatory_design(ROOT)
    inference_profile = (ROOT / str(design["inference_profile_path"])).resolve()
    dataset_roots: dict[str, Path] = {}
    if args.adcs_root:
        dataset_roots["adcs"] = args.adcs_root.resolve()
    if args.phm_root:
        dataset_roots["phm"] = args.phm_root.resolve()

    environment_lock_path = args.environment_lock.resolve()
    environment_lock = load_confirmatory_python_environment_lock(environment_lock_path)
    pre_attestation, pre_attestation_source, pre_runtime_admission = _acquire_runtime_identity(
        args=args,
        environment_lock=environment_lock,
    )
    if pre_attestation is not None:
        _write(output_dir / "model_runtime_attestation_pre.json", pre_attestation)
    _write(output_dir / "runtime_identity_admission_pre.json", pre_runtime_admission)

    models, model_detail, endpoint_ok = _probe_models(args.vllm_url)
    readiness = confirmatory_readiness(
        ROOT,
        dataset_roots=dataset_roots or None,
        live_model_available=endpoint_ok,
        live_model_detail=model_detail,
        requested_model_id=args.vllm_model,
        observed_model_ids=models,
        case_manifest_path=(args.case_manifest.resolve() if args.case_manifest else None),
        require_readonly_datasets=args.require_readonly_datasets,
        runtime_identity_admission=pre_runtime_admission,
        enforce_runtime_identity=True,
    )
    readiness["runtime_identity_attestation_source"] = pre_attestation_source
    readiness["environment_lock_path"] = str(environment_lock_path)
    _write(output_dir / "readiness.json", readiness)
    if readiness["status"] != "READY":
        print(json.dumps(readiness, ensure_ascii=False, indent=2))
        return 2

    snapshot_path = args.dataset_snapshot_receipt.resolve()
    if not snapshot_path.is_file():
        snapshot_error = {
            "schema_version": "astrograph-llm-method-confirmatory-dataset-snapshot-check.v1",
            "status": "DRIFTED",
            "drift_codes": ["DATASET_SNAPSHOT_RECEIPT_MISSING"],
            "path": str(snapshot_path),
        }
        _write(output_dir / "dataset_snapshot_admission.json", snapshot_error)
        print(json.dumps(snapshot_error, ensure_ascii=False, indent=2))
        return 2
    snapshot_receipt = json.loads(snapshot_path.read_text(encoding="utf-8"))
    snapshot_check = verify_confirmatory_dataset_snapshot_receipt(
        snapshot_receipt=snapshot_receipt,
        current_readiness=readiness,
        require_readonly_datasets=args.require_readonly_datasets,
    )
    _write(output_dir / "dataset_snapshot_admission.json", snapshot_check)
    if snapshot_check["status"] != "STABLE":
        print(json.dumps(snapshot_check, ensure_ascii=False, indent=2))
        return 2

    receipt = build_confirmatory_execution_receipt(
        ROOT,
        readiness=readiness,
        vllm_url=args.vllm_url,
        vllm_model=args.vllm_model,
        dataset_snapshot_receipt=snapshot_receipt,
        runtime_identity_admission=pre_runtime_admission,
    )
    # Audit paths/sources are persisted separately so the self-hashed execution receipt remains immutable.
    _write(output_dir / "execution_receipt.json", receipt)
    if args.dry_run:
        print(json.dumps(receipt, ensure_ascii=False, indent=2))
        return 0

    env = os.environ.copy()
    if dataset_roots.get("adcs"):
        env["ASTROGRAPH_ADCS_V522_DATA_ROOT"] = str(dataset_roots["adcs"])
    if dataset_roots.get("phm"):
        env["ASTROGRAPH_PHM_V60_DATA_ROOT"] = str(dataset_roots["phm"])
    case_manifest = Path(readiness["case_manifest_path"]).resolve()
    report_name = "report.json"
    command = [
        sys.executable,
        str(ROOT / "scripts/experiments/run_llm_method_ablation.py"),
        "--output-dir", str(output_dir),
        "--vllm-url", args.vllm_url,
        "--vllm-model", args.vllm_model,
        "--case-manifest", str(case_manifest),
        "--inference-profile", str(inference_profile),
        "--report-name", report_name,
    ]
    command_receipt = {
        "schema_version": "astrograph-llm-method-confirmatory-command.v2",
        "campaign_id": design["campaign_id"],
        "argv": command,
        "execution_receipt_sha256": receipt["receipt_sha256"],
        "runtime_identity_sha256": pre_runtime_admission.get("runtime_identity_sha256"),
        "inference_profile_sha256": (readiness.get("inference_profile") or {}).get("sha256"),
    }
    _write(output_dir / "command_receipt.json", command_receipt)
    completed = subprocess.run(command, cwd=ROOT, env=env, check=False)

    # Re-observe the entire runtime identity after A0-A7. For a local spec this rehashes model,
    # tokenizer and server artifacts; for a remote sidecar this performs a fresh HTTP fetch.
    post_attestation, post_attestation_source, post_runtime_admission = _acquire_runtime_identity(
        args=args,
        environment_lock=environment_lock,
    )
    if post_attestation is not None:
        _write(output_dir / "model_runtime_attestation_post.json", post_attestation)
    _write(output_dir / "runtime_identity_admission_post.json", post_runtime_admission)

    post_models, post_model_detail, post_endpoint_ok = _probe_models(args.vllm_url)
    post_readiness = confirmatory_readiness(
        ROOT,
        dataset_roots=dataset_roots or None,
        live_model_available=post_endpoint_ok,
        live_model_detail=post_model_detail,
        requested_model_id=args.vllm_model,
        observed_model_ids=post_models,
        case_manifest_path=case_manifest,
        require_readonly_datasets=args.require_readonly_datasets,
        runtime_identity_admission=post_runtime_admission,
        enforce_runtime_identity=True,
    )
    post_readiness["runtime_identity_attestation_source"] = post_attestation_source
    _write(output_dir / "post_execution_readiness.json", post_readiness)

    post_snapshot_check = verify_confirmatory_dataset_snapshot_receipt(
        snapshot_receipt=snapshot_receipt,
        current_readiness=post_readiness,
        require_readonly_datasets=args.require_readonly_datasets,
    )
    _write(output_dir / "post_execution_dataset_snapshot.json", post_snapshot_check)
    execution_identity_check = verify_confirmatory_execution_identity(
        execution_receipt=receipt,
        current_readiness=post_readiness,
        current_runtime_identity_admission=post_runtime_admission,
    )
    runtime_drift_check = verify_confirmatory_runtime_identity_drift(
        pre_admission=pre_runtime_admission,
        post_admission=post_runtime_admission,
    )
    if post_snapshot_check["status"] != "STABLE":
        snapshot_identity_check = {
            "schema_version": "astrograph-llm-method-confirmatory-snapshot-identity-gate.v1",
            "status": "DRIFTED",
            "drift_codes": [f"SNAPSHOT:{item}" for item in (post_snapshot_check.get("drift_codes") or [])],
        }
    else:
        snapshot_identity_check = {
            "schema_version": "astrograph-llm-method-confirmatory-snapshot-identity-gate.v1",
            "status": "STABLE",
            "drift_codes": [],
        }
    identity_check = _merge_identity_checks(execution_identity_check, runtime_drift_check, snapshot_identity_check)
    _write(output_dir / "post_execution_identity.json", identity_check)

    if completed.returncode != 0:
        _write(output_dir / "campaign_status.json", {
            "schema_version": "astrograph-llm-method-confirmatory-status.v2",
            "status": ("FAILED_EXECUTION_WITH_IDENTITY_DRIFT" if identity_check["status"] != "STABLE" else "FAILED_EXECUTION"),
            "returncode": completed.returncode,
            "identity_status": identity_check["status"],
            "execution_receipt_sha256": receipt["receipt_sha256"],
        })
        return completed.returncode or 1
    if identity_check["status"] != "STABLE":
        _write(output_dir / "campaign_status.json", {
            "schema_version": "astrograph-llm-method-confirmatory-status.v2",
            "status": "FAILED_IDENTITY_DRIFT",
            "identity_status": identity_check["status"],
            "drift_codes": identity_check["drift_codes"],
            "execution_receipt_sha256": receipt["receipt_sha256"],
        })
        return 3

    report_path = output_dir / report_name
    report = json.loads(report_path.read_text(encoding="utf-8"))
    if report.get("experiment_scope") != "FROZEN_CONFIRMATORY_CASE_MANIFEST":
        raise RuntimeError("confirmatory report does not declare frozen manifest scope")
    expected_case_ids = sorted(
        str(item.get("case_id"))
        for item in json.loads(case_manifest.read_text(encoding="utf-8")).get("cases", [])
        if item.get("case_id")
    )
    report_case_ids = sorted(str(item) for item in (report.get("case_ids") or []))
    if len(report_case_ids) != int(design["case_selection"]["expected_case_count"]):
        raise RuntimeError("confirmatory report denominator differs from frozen design")
    if report_case_ids != expected_case_ids:
        raise RuntimeError("confirmatory report case identities differ from frozen manifest")
    decision = evaluate_confirmatory_promotion(report, design)
    decision.update({
        "campaign_id": design["campaign_id"],
        "execution_receipt_sha256": receipt["receipt_sha256"],
        "post_execution_identity_status": identity_check["status"],
        "report_path": report_name,
    })
    _write(output_dir / "promotion_decision.json", decision)
    _write(output_dir / "campaign_status.json", {
        "schema_version": "astrograph-llm-method-confirmatory-status.v2",
        "status": "COMPLETED",
        "promotion_review_gate": decision["status"],
        "probe_promotion_review_gate": (decision.get("probe_promotion_review") or {}).get("status"),
        "identity_status": identity_check["status"],
        "execution_receipt_sha256": receipt["receipt_sha256"],
    })
    print(json.dumps(decision, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
