#!/usr/bin/env python3
"""Offline Chromium smoke for the real Mission Console bundled in AstroGraph.

Uses REAL report and public-graph API data generated by the server-side TestClient;
substitutes only the browser transport because this CI's Chromium policy blocks
all URL navigation, including loopback and file URLs. This is not a live-HTTP test.
Usage: python scripts/evaluation/smoke_mission_console_browser.py
"""
from __future__ import annotations

import json
import os
import tempfile
from pathlib import Path

from fastapi.testclient import TestClient

from astrograph.api import create_app

ROOT = Path(__file__).resolve().parents[2]
RESOURCES = ROOT / "src" / "astrograph" / "resources"


def real_backend_fixtures() -> tuple[dict, dict, dict]:
    previous = {name: os.environ.get(name) for name in (
        "ASTROGRAPH_PLATFORM_ROOT", "ASTROGRAPH_AUTH_MODE", "ASTROGRAPH_API_TOKENS_JSON")}
    try:
        with tempfile.TemporaryDirectory(prefix="astrograph-browser-smoke-") as tmp:
            os.environ["ASTROGRAPH_PLATFORM_ROOT"] = str(Path(tmp) / "platform")
            os.environ["ASTROGRAPH_AUTH_MODE"] = "local"
            os.environ.pop("ASTROGRAPH_API_TOKENS_JSON", None)
            with TestClient(create_app()) as api:
                demos = api.get("/platform/mission/assets/mission_demo_cases.json").json()
                example = demos["cases"][0]
                job = api.post("/v1/platform/jobs", json={"task": "从实际输入材料生成报告", "work_mode": "normal"}).json()
                job_id = job["job_id"]
                manifest = {"schema_version": "astrograph-result-log-review.v1", "equipment_scope": example["equipment_scope"]}
                for role, entries in example["files"].items():
                    manifest[role] = [e["name"] for e in entries]
                    for entry in entries:
                        result = api.put(f"/v1/platform/jobs/{job_id}/files/{entry['name']}", content=entry["content"].encode())
                        assert result.status_code == 200, result.text
                r = api.put(f"/v1/platform/jobs/{job_id}/files/analysis_input.json", content=json.dumps(manifest).encode())
                assert r.status_code == 200, r.text
                assert api.post(f"/v1/platform/jobs/{job_id}/preflight").json()["can_start"]
                assert api.post(f"/v1/platform/jobs/{job_id}/run").json()["status"] == "SUCCEEDED"
                report = api.get(f"/v1/platform/jobs/{job_id}/report").json()
                graph = api.get("/v1/platform/knowledge/public-seed").json()
                return demos, report, graph
    finally:
        for name, value in previous.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value


def composite_html(demos: dict, report: dict, graph: dict) -> str:
    page = (RESOURCES / "mission_console.html").read_text(encoding="utf-8")
    css = (RESOURCES / "mission_console.css").read_text(encoding="utf-8")
    js = (RESOURCES / "mission_console.js").read_text(encoding="utf-8")
    # Browser policy blocks URL navigation, so inline the EXACT shipped CSS and JS.
    import re
    page = re.sub(r'<link rel="stylesheet" href="/platform/mission/assets/mission_console\.css\?v=[^"]+"\s*/>',
                  lambda m: "<style>" + css + "</style>", page)
    page = re.sub(r'<script type="module" src="/platform/mission/assets/mission_console\.js\?v=[^"]+"></script>',
                  lambda m: "<script>" + js + "</script>", page)
    fixture = "\n".join(
        f"window.{name}={json.dumps(value, ensure_ascii=False).replace('</', '<\\/')};"
        for name, value in (("__demoFixture", demos), ("__reportFixture", report), ("__graphFixture", graph))
    )
    transport = r"""
window.__role='admin';window.__expert=false;window.__calls=[];
window.fetch=async(url,init={})=>{
 const path=String(url),method=(init.method||'GET').toUpperCase();
 window.__calls.push({path,method});
 let status=200,result={};
 if(path.endsWith('/mission/identity'))result={mode:'bearer',subject:'demo:'+window.__role,roles:[window.__role],permissions:{read:true,analyze:window.__role!=='viewer',settings:window.__role==='admin'}};
 else if(path.includes('mission_demo_cases.json'))result=window.__demoFixture;
 else if(path.includes('/knowledge/public-seed'))result=window.__graphFixture;
 else if(path.includes('/jobs/')&&path.endsWith('/report'))result=window.__reportFixture;
 else if(path.includes('/jobs/')&&path.endsWith('/report.md'))return new Response('# 航天器故障分析报告\n模拟运输层返回；实际后端已另测', {status:200,headers:{'content-type':'text/markdown'}});
 else if(path.endsWith('/v1/platform/jobs')&&method==='POST')result={job_id:window.__reportFixture.job_id};
 else if(path.includes('/files/')&&method==='PUT')result={accepted:true};
 else if(path.endsWith('/preflight')&&method==='POST')result={can_start:true};
 else if(path.endsWith('/start')&&method==='POST')result={status:'QUEUED'};
 else if(path.endsWith('/v1/platform/jobs/'+window.__reportFixture.job_id))result={status:'SUCCEEDED',stage:'COMPLETED'};
 else if(path.includes('/manual-review/status'))result={status:'PENDING',total_count:1,reviewed_count:0};
 else if(path.includes('/review-session')){if(method==='POST')window.__expert=true;else if(method==='DELETE')window.__expert=false;result={authenticated:window.__expert,reviewer:window.__expert?'expert1':null,csrf:window.__expert?'test-csrf':null}}
 else if(path.includes('/report-reviews?'))result={items:[{job_id:window.__reportFixture.job_id,status:'PENDING',reviewed_count:0,total_count:1}]};
 else if(path.includes('/report-reviews/')&&method==='GET')result={job_id:window.__reportFixture.job_id,status:'PENDING',report_sha256:'test-sha',revision:0,candidates:[{fault_id:window.__reportFixture.analysis.result_log_review.candidates[0].fault_id,fault_name:'反作用轮摩擦增大'}]};
 else if(path.includes('/report-reviews/')&&method==='POST')result={status:'REVIEWED'};
 else if(path.includes('/v1/platform/overview'))result={recent_jobs:[{job_id:window.__reportFixture.job_id,status:'SUCCEEDED',task:'演示故障任务',artifact_kind:'RESULT_LOG_REVIEW'}]};
 else if(path.includes('/settings/knowledge-engine'))result={revision:1,settings:{embedding_model:'',vector_backend:'sqlite',qdrant_url:'',qdrant_collection:'',ocr_engine:'disabled',ocr_languages:'chi_sim+eng'}};
 else if(path.includes('/settings/llm/profiles'))result={profile:{profile_id:'p-test'},secret_persisted:true,active:true};
 else if(path.includes('/settings/llm'))result={provider:'local-openai-compatible',base_url:'http://127.0.0.1:8000/v1',model:'local-model',persists_across_restart:false};
 else result={};
 return new Response(JSON.stringify(result),{status,headers:{'content-type':'application/json'}});
};
"""
    return page.replace("</head>", "<script>" + fixture + transport + "</script></head>", 1)


def main() -> None:
    from playwright.sync_api import sync_playwright

    demos, report, graph = real_backend_fixtures()
    assert report["analysis"]["result_log_review"]["candidates"]
    html = composite_html(demos, report, graph)
    previews = Path(os.environ['ASTROGRAPH_MISSION_PREVIEWS']) if os.environ.get('ASTROGRAPH_MISSION_PREVIEWS') else None
    if previews: previews.mkdir(parents=True, exist_ok=True)
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(headless=True, args=["--no-sandbox"], **({"executable_path": os.environ["ASTROGRAPH_CHROMIUM_EXECUTABLE"]} if os.environ.get("ASTROGRAPH_CHROMIUM_EXECUTABLE") else {}))
        page = browser.new_page(viewport={"width": 1440, "height": 900}, accept_downloads=True)
        failures = []
        page.on("pageerror", lambda error: failures.append(str(error)))
        page.set_content(html, wait_until="load", timeout=30000)
        page.wait_for_function("document.querySelector('#identity-label').textContent.includes('管理员')")
        assert page.locator('#page-label').inner_text() == '智能助理'
        assert page.locator('[data-route="settings"]').is_visible()
        if previews: page.wait_for_timeout(450); page.screenshot(path=str(previews/'01_智能助理_深色.png'), full_page=True)
        page.locator('#theme-select').select_option('light')
        assert page.locator('body').get_attribute('data-theme') == 'light'
        page.locator('#font-select').select_option('large')
        assert page.locator('body').get_attribute('data-size') == 'large'
        if previews: page.wait_for_timeout(450); page.screenshot(path=str(previews/'02_智能助理_浅色大字.png'), full_page=True)
        page.locator('[data-route="graph"]').click()
        page.wait_for_function("document.querySelectorAll('[data-graph-code]').length > 0")
        assert '公开' in page.locator('#graph-detail').inner_text()
        if previews: page.wait_for_timeout(450); page.screenshot(path=str(previews/'03_知识图谱.png'), full_page=True)
        page.locator('[data-route="upload"]').click()
        page.locator('#open-demo').click()
        page.locator('[data-demo-case="TC01"]').click()
        assert page.locator('#upload-file-count').inner_text() == '3'
        page.locator('#mission-preflight').click()
        page.wait_for_function("!document.querySelector('#mission-start').disabled")
        page.locator('#mission-start').click()
        page.wait_for_function("document.querySelector('#page-label').textContent==='原因与处置'")
        assert '可能原因' in page.locator('#report-content').inner_text()
        if previews: page.wait_for_timeout(450); page.screenshot(path=str(previews/'04_原因处置报告.png'), full_page=True)
        assert page.locator('#report-export-json').is_visible()
        with page.expect_download(timeout=8000) as receipt:
            page.locator('#report-export-json').click()
        assert receipt.value.suggested_filename.endswith('report.json')
        page.locator('[data-report-tab="reasoning"]').click()
        assert '多跳推理' in page.locator('#report-content').inner_text()
        page.locator('[data-route="assistant"]').click()
        page.locator('#chat-text').fill('当前故障的可能原因是什么？')
        page.locator('#chat-form .send-btn').click()
        assert page.locator('.message.assistant').count()==1
        assert '未确诊' in page.locator('.message.assistant .bubble').inner_text()
        page.locator('[data-route="report"]').click()
        page.locator('#report-review-jump').click()
        page.locator('#expert-credential').fill('test-review-credential')
        page.locator('#expert-login').click()
        page.wait_for_function("document.querySelector('#expert-status').textContent.includes('expert1')")
        page.wait_for_function("document.querySelectorAll('[data-review-fault]').length > 0")
        page.locator('[data-review-fault] select[name=decision]').select_option('EVIDENCE_INSUFFICIENT')
        page.locator('[data-review-fault] textarea[name=note]').fill('目前没有完成型号级独立核验，应补充轮速和电流证据。')
        page.locator('[data-review-fault] button[type=submit]').click()
        page.wait_for_function("window.__calls.some(x=>x.path.includes('/report-reviews/')&&x.path.endsWith('/decisions')&&x.method==='POST')")
        page.locator('[data-route="settings"]').click()
        page.locator('#llm-persist').check()
        assert page.locator('#llm-profile-name-field').is_visible()
        page.locator('#llm-profile-name').fill('演示模型服务')
        page.locator('#llm-form button[type="submit"]').click()
        page.wait_for_function("window.__calls.some(x=>x.path.endsWith('/settings/llm/profiles') && x.method==='POST')")
        # Changing authenticated identity cannot leave the old user report in DOM or memory.
        page.evaluate("window.__role='viewer'; refreshIdentity()")
        page.wait_for_function("document.querySelector('#identity-label').textContent.includes('只读访客')")
        assert not page.locator('[data-route="settings"]').is_visible()
        assert not page.locator('[data-route="upload"]').is_visible()
        page.locator('[data-route="report"]').click()
        assert '请选择已完成' in page.locator('#report-content').inner_text()
        assert page.evaluate("S.report===null && S.jobId==='' && S.preflightId==='' ")
        page.set_viewport_size({"width":390,"height":844})
        assert page.evaluate("document.documentElement.scrollWidth<=window.innerWidth+2"), 'mobile horizontal overflow'
        assert not failures, '\n'.join(failures)
        print('PASS: actual API report + graph data; UI upload, tabs, chat, persistence setting, role isolation, expert review, export, mobile')
        browser.close()

if __name__ == "__main__":
    main()
